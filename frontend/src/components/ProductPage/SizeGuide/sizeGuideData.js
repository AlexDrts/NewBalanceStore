export function getGuideType(product) {
    const gender = String(product.gender).toLowerCase() === "women" ? "women" : "men";

    return {
        kind: product.type === "Footwear" ? "shoes" : "apparel",
        gender
    };
}

export function getGuideTitle({ kind, gender }) {
    if (kind === "shoes") return gender === "women" ? "Women's" : "Men's/Unisex";
    return gender === "women" ? "Women's Apparel" : "Men's Apparel";
}

export function getShoeSizeTable(gender) {
    if (gender === "women") {
        return {
            columns: ["Women's US Size", "Men's US Size", ...SHOE_SIZE_COLUMNS],
            rows: SHOE_SIZES
                .filter(([, women]) => women !== "-")
                .map(([men, women, ...rest]) => [women, men, ...rest])
        };
    }

    return {
        columns: ["Men's US Size", "Women's US Size", ...SHOE_SIZE_COLUMNS],
        rows: SHOE_SIZES.map(row => [...row])
    };
}

export function getWidthTable(gender) {
    const names = WIDTH_NAMES[gender];
    const columns = [gender === "women" ? "Women's US Size" : "Men's US Size"];

    names.forEach(name => columns.push(`${name} (cm)`, `${name} (in)`));

    const rows = WIDTH_SIZES.map(([size, ...widths]) => [
        gender === "women" ? size + WOMEN_OFFSET : size,
        ...widths
    ]);

    return { columns, rows };
}

export function formatMeasurement(range, unit) {
    const convert = value => (unit === "cm" ? Math.round(value * 2.54) : value);
    const [from, to] = range.map(convert);

    return from === to ? `${from}` : `${from}–${to}`;
}